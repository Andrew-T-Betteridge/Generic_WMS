BEGIN;

-- ---------------------------------------------------------------------------
-- DYNETIC WMS Website/API V3
-- Accounts, saved addresses, favourites, secure ownership and payment events.
-- Authentication remains provider-neutral: only provider + subject are stored.
-- ---------------------------------------------------------------------------

ALTER TABLE core.ORDER_HEADER
    ADD COLUMN IF NOT EXISTS ACCOUNT_ID UUID,
    ADD COLUMN IF NOT EXISTS PAYMENT_DUE_DSTAMP TIMESTAMPTZ;

ALTER TABLE core.CUSTOMER_INTEREST
    ADD COLUMN IF NOT EXISTS ACCOUNT_ID UUID;

ALTER TABLE core.STOCK_RESERVATION
    ADD COLUMN IF NOT EXISTS ACCOUNT_ID UUID;

ALTER TABLE core.PAYMENT_TRANSACTION
    ADD COLUMN IF NOT EXISTS ACCOUNT_ID UUID,
    ADD COLUMN IF NOT EXISTS CAPTURED_AMOUNT NUMERIC(12,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS REFUNDED_AMOUNT NUMERIC(12,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS PROVIDER_STATUS VARCHAR(50),
    ADD COLUMN IF NOT EXISTS LAST_EVENT_TYPE VARCHAR(100),
    ADD COLUMN IF NOT EXISTS LAST_EVENT_DSTAMP TIMESTAMPTZ;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname='FK_ORDER_HEADER_ACCOUNT'
    ) THEN
        ALTER TABLE core.ORDER_HEADER
        ADD CONSTRAINT FK_ORDER_HEADER_ACCOUNT
        FOREIGN KEY (ACCOUNT_ID) REFERENCES core.CUSTOMER_ACCOUNT(ACCOUNT_ID);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname='FK_CUSTOMER_INTEREST_ACCOUNT'
    ) THEN
        ALTER TABLE core.CUSTOMER_INTEREST
        ADD CONSTRAINT FK_CUSTOMER_INTEREST_ACCOUNT
        FOREIGN KEY (ACCOUNT_ID) REFERENCES core.CUSTOMER_ACCOUNT(ACCOUNT_ID);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname='FK_STOCK_RESERVATION_ACCOUNT'
    ) THEN
        ALTER TABLE core.STOCK_RESERVATION
        ADD CONSTRAINT FK_STOCK_RESERVATION_ACCOUNT
        FOREIGN KEY (ACCOUNT_ID) REFERENCES core.CUSTOMER_ACCOUNT(ACCOUNT_ID);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname='FK_PAYMENT_TRANSACTION_ACCOUNT'
    ) THEN
        ALTER TABLE core.PAYMENT_TRANSACTION
        ADD CONSTRAINT FK_PAYMENT_TRANSACTION_ACCOUNT
        FOREIGN KEY (ACCOUNT_ID) REFERENCES core.CUSTOMER_ACCOUNT(ACCOUNT_ID);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS core.CUSTOMER_ACCOUNT_ADDRESS (
    ACCOUNT_ID UUID NOT NULL,
    CLIENT_ID VARCHAR(30) NOT NULL,
    ADDRESS_ID VARCHAR(15) NOT NULL,
    ADDRESS_LABEL VARCHAR(50),
    DEFAULT_DELIVERY BOOLEAN NOT NULL DEFAULT FALSE,
    DEFAULT_BILLING BOOLEAN NOT NULL DEFAULT FALSE,
    ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    LAST_UPDATE_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (ACCOUNT_ID,ADDRESS_ID),
    CONSTRAINT FK_ACCOUNT_ADDRESS_ACCOUNT
        FOREIGN KEY (ACCOUNT_ID) REFERENCES core.CUSTOMER_ACCOUNT(ACCOUNT_ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_ACCOUNT_ADDRESS_ADDRESS
        FOREIGN KEY (CLIENT_ID,ADDRESS_ID) REFERENCES core.ADDRESS(CLIENT_ID,ADDRESS_ID)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS core.PRODUCT_FAVOURITE (
    ACCOUNT_ID UUID NOT NULL,
    CLIENT_ID VARCHAR(30) NOT NULL,
    PRODUCT_ID VARCHAR(50) NOT NULL,
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (ACCOUNT_ID,PRODUCT_ID),
    CONSTRAINT FK_PRODUCT_FAVOURITE_ACCOUNT
        FOREIGN KEY (ACCOUNT_ID) REFERENCES core.CUSTOMER_ACCOUNT(ACCOUNT_ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_PRODUCT_FAVOURITE_PRODUCT
        FOREIGN KEY (CLIENT_ID,PRODUCT_ID) REFERENCES core.PRODUCT(CLIENT_ID,PRODUCT_ID)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS audit.PAYMENT_EVENT (
    PAYMENT_EVENT_KEY BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENT_ID VARCHAR(30) NOT NULL,
    PROVIDER VARCHAR(30) NOT NULL,
    PROVIDER_EVENT_ID VARCHAR(200) NOT NULL,
    EVENT_TYPE VARCHAR(100) NOT NULL,
    PROVIDER_REFERENCE VARCHAR(200),
    PAYMENT_ID UUID,
    EVENT_STATUS VARCHAR(30) NOT NULL DEFAULT 'RECEIVED',
    EVENT_PAYLOAD JSONB NOT NULL DEFAULT '{}'::jsonb,
    ERROR_TEXT VARCHAR(500),
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    PROCESSED_DSTAMP TIMESTAMPTZ,
    CONSTRAINT UQ_PAYMENT_EVENT UNIQUE (CLIENT_ID,PROVIDER,PROVIDER_EVENT_ID),
    CONSTRAINT FK_PAYMENT_EVENT_PAYMENT
        FOREIGN KEY (PAYMENT_ID) REFERENCES core.PAYMENT_TRANSACTION(PAYMENT_ID)
);

CREATE TABLE IF NOT EXISTS audit.API_SECURITY_EVENT (
    SECURITY_EVENT_KEY BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENT_ID VARCHAR(30),
    EVENT_TYPE VARCHAR(50) NOT NULL,
    AUTH_PROVIDER VARCHAR(50),
    AUTH_SUBJECT VARCHAR(200),
    ROUTE VARCHAR(250),
    RESOURCE_TYPE VARCHAR(50),
    RESOURCE_ID VARCHAR(200),
    RESULT VARCHAR(30) NOT NULL,
    DETAIL VARCHAR(500),
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMIT;
