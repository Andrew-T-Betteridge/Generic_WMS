    CONSTRAINT UQ_GIFT_CARD_CODE UNIQUE (CLIENT_ID,GIFT_CODE),
    CONSTRAINT FK_GIFT_CARD_CLIENT FOREIGN KEY (CLIENT_ID) REFERENCES core.CLIENT (CLIENT_ID),
