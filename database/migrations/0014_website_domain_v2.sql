CREATE TABLE IF NOT EXISTS core.PAYMENT_TRANSACTION (
    PAYMENT_ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    CLIENT_ID VARCHAR(30) NOT NULL,
    PROVIDER VARCHAR(30) NOT NULL,
    REFERENCE_TYPE VARCHAR(30) NOT NULL,
    REFERENCE_ID VARCHAR(100) NOT NULL,
    PROVIDER_REFERENCE VARCHAR(200),
    AMOUNT NUMERIC(12,2) NOT NULL,
    CURRENCY VARCHAR(3) NOT NULL DEFAULT 'GBP',
    STATUS VARCHAR(30) NOT NULL DEFAULT 'CREATED',
    IDEMPOTENCY_KEY VARCHAR(100),
    FAILURE_CODE VARCHAR(100),
    FAILURE_TEXT VARCHAR(500),
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    LAST_UPDATE_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT FK_PAYMENT_TRANSACTION_CLIENT FOREIGN KEY (CLIENT_ID) REFERENCES core.CLIENT (CLIENT_ID),
