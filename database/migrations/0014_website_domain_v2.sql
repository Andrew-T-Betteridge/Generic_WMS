    ADD COLUMN IF NOT EXISTS SALE_TYPE VARCHAR(30) NOT NULL DEFAULT 'STANDARD',
    ADD COLUMN IF NOT EXISTS AVAILABILITY_STATE VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
    ADD COLUMN IF NOT EXISTS EXPECTED_AVAILABLE_FROM DATE,
    ADD COLUMN IF NOT EXISTS EXPECTED_AVAILABLE_TO DATE,
    ADD COLUMN IF NOT EXISTS WEB_METADATA JSONB NOT NULL DEFAULT '{}'::jsonb,
    ADD COLUMN IF NOT EXISTS MIN_ORDER_QTY NUMERIC(15,6) NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS MAX_ORDER_QTY NUMERIC(15,6),
    ADD COLUMN IF NOT EXISTS QTY_INCREMENT NUMERIC(15,6) NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS core.PRODUCT_SEARCH_ALIAS (
    SEARCH_ALIAS_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENT_ID VARCHAR(30) NOT NULL,
    PRODUCT_ID VARCHAR(50) NOT NULL,
    ALIAS_TEXT VARCHAR(250) NOT NULL,
    ALIAS_TYPE VARCHAR(30) NOT NULL DEFAULT 'OTHER',
    ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT FK_PRODUCT_SEARCH_ALIAS_PRODUCT
        FOREIGN KEY (CLIENT_ID,PRODUCT_ID)
        REFERENCES core.PRODUCT (CLIENT_ID,PRODUCT_ID)
        ON DELETE CASCADE,
    CONSTRAINT UQ_PRODUCT_SEARCH_ALIAS
        UNIQUE (CLIENT_ID,PRODUCT_ID,ALIAS_TEXT)
);

CREATE TABLE IF NOT EXISTS core.PRODUCT_MEDIA (
    MEDIA_ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    CLIENT_ID VARCHAR(30) NOT NULL,
    PRODUCT_ID VARCHAR(50) NOT NULL,
    SKU_ID VARCHAR(50),
    MEDIA_TYPE VARCHAR(20) NOT NULL,
    MEDIA_ROLE VARCHAR(30) NOT NULL DEFAULT 'GALLERY',
    MEDIA_URL TEXT NOT NULL,
    THUMBNAIL_URL TEXT,
    ALT_TEXT VARCHAR(300),
    CAPTION VARCHAR(500),
    SORT_SEQUENCE INTEGER NOT NULL DEFAULT 100,
    ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    LAST_UPDATE_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT FK_PRODUCT_MEDIA_PRODUCT
        FOREIGN KEY (CLIENT_ID,PRODUCT_ID)
        REFERENCES core.PRODUCT (CLIENT_ID,PRODUCT_ID)
        ON DELETE CASCADE,
    CONSTRAINT CK_PRODUCT_MEDIA_TYPE
        CHECK (MEDIA_TYPE IN ('IMAGE','VIDEO')),
    CONSTRAINT CK_PRODUCT_MEDIA_ROLE
        CHECK (MEDIA_ROLE IN ('HERO','GALLERY','REPRESENTATIVE','CURRENT_STOCK','HOVER'))
);

CREATE TABLE IF NOT EXISTS core.CUSTOMER_INTEREST (
    INTEREST_ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    CLIENT_ID VARCHAR(30) NOT NULL,
    INTEREST_TYPE VARCHAR(30) NOT NULL,
    PRODUCT_ID VARCHAR(50) NOT NULL,
    SKU_ID VARCHAR(50),
    REQUESTED_QTY NUMERIC(15,6),
    CONTACT_NAME VARCHAR(100),
    EMAIL VARCHAR(254) NOT NULL,
    PHONE VARCHAR(40),
    PREFERRED_CHANNEL VARCHAR(20) NOT NULL DEFAULT 'EMAIL',
    CONSENT_TO_NOTIFY BOOLEAN NOT NULL DEFAULT TRUE,
    STATUS VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    NOTIFIED_DSTAMP TIMESTAMPTZ,
    CONVERTED_ORDER_ID VARCHAR(20),
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    LAST_UPDATE_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT FK_CUSTOMER_INTEREST_PRODUCT
        FOREIGN KEY (CLIENT_ID,PRODUCT_ID)
        REFERENCES core.PRODUCT (CLIENT_ID,PRODUCT_ID),
    CONSTRAINT CK_CUSTOMER_INTEREST_TYPE
        CHECK (INTEREST_TYPE IN ('WAITLIST','GROWING_STOCK')),
    CONSTRAINT CK_CUSTOMER_INTEREST_STATUS
        CHECK (STATUS IN ('ACTIVE','NOTIFIED','CONVERTED','CLOSED')),
    CONSTRAINT CK_CUSTOMER_INTEREST_CHANNEL
        CHECK (PREFERRED_CHANNEL IN ('EMAIL','SMS','WHATSAPP'))
);

CREATE TABLE IF NOT EXISTS core.STOCK_RESERVATION (
    RESERVATION_ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    CLIENT_ID VARCHAR(30) NOT NULL,
    SOURCE_SYSTEM VARCHAR(50) NOT NULL DEFAULT 'WEBSITE',
    SOURCE_REFERENCE VARCHAR(100),
    CUSTOMER_ID VARCHAR(15),
    CONTACT_NAME VARCHAR(100),
    EMAIL VARCHAR(254) NOT NULL,
    PHONE VARCHAR(40),
    STATUS VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    FULFILMENT_METHOD VARCHAR(30),
    NOTES VARCHAR(500),
    EXPIRES_DSTAMP TIMESTAMPTZ NOT NULL,
    CONVERTED_ORDER_ID VARCHAR(20),
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    LAST_UPDATE_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT FK_STOCK_RESERVATION_CLIENT
        FOREIGN KEY (CLIENT_ID) REFERENCES core.CLIENT (CLIENT_ID),
    CONSTRAINT CK_STOCK_RESERVATION_STATUS
        CHECK (STATUS IN ('ACTIVE','CONVERTED','RELEASED','EXPIRED','CANCELLED')),
    CONSTRAINT UQ_STOCK_RESERVATION_SOURCE
        UNIQUE (CLIENT_ID,SOURCE_SYSTEM,SOURCE_REFERENCE)
);

CREATE TABLE IF NOT EXISTS core.STOCK_RESERVATION_LINE (
    RESERVATION_LINE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RESERVATION_ID UUID NOT NULL,
    CLIENT_ID VARCHAR(30) NOT NULL,
    SKU_ID VARCHAR(50) NOT NULL,
    QTY_RESERVED NUMERIC(15,6) NOT NULL,
    UNIT_PRICE NUMERIC(12,2),
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT FK_STOCK_RESERVATION_LINE_HEADER
        FOREIGN KEY (RESERVATION_ID)
        REFERENCES core.STOCK_RESERVATION (RESERVATION_ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_STOCK_RESERVATION_LINE_SKU
        FOREIGN KEY (CLIENT_ID,SKU_ID)
        REFERENCES core.SKU (CLIENT_ID,SKU_ID),
    CONSTRAINT CK_STOCK_RESERVATION_LINE_QTY
        CHECK (QTY_RESERVED > 0)
);

CREATE TABLE IF NOT EXISTS core.STOCK_RESERVATION_INVENTORY (
    RESERVATION_LINE_ID BIGINT NOT NULL,
    INVENTORY_KEY BIGINT NOT NULL,
    QTY_RESERVED NUMERIC(15,6) NOT NULL,
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (RESERVATION_LINE_ID,INVENTORY_KEY),
    CONSTRAINT FK_RESERVATION_INVENTORY_LINE
        FOREIGN KEY (RESERVATION_LINE_ID)
        REFERENCES core.STOCK_RESERVATION_LINE (RESERVATION_LINE_ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_RESERVATION_INVENTORY_STOCK
        FOREIGN KEY (INVENTORY_KEY)
        REFERENCES core.INVENTORY (KEY),
    CONSTRAINT CK_RESERVATION_INVENTORY_QTY CHECK (QTY_RESERVED > 0)
);

