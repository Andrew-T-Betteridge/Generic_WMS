    CONSTRAINT CK_PAYMENT_REFERENCE_TYPE CHECK (REFERENCE_TYPE IN ('ORDER','RESERVATION','GIFT_CARD')),
    CONSTRAINT CK_PAYMENT_STATUS CHECK (STATUS IN ('CREATED','PENDING','AUTHORISED','PAID','FAILED','CANCELLED','REFUNDED','PART_REFUNDED')),
    CONSTRAINT UQ_PAYMENT_IDEMPOTENCY UNIQUE (CLIENT_ID,PROVIDER,IDEMPOTENCY_KEY)
);

