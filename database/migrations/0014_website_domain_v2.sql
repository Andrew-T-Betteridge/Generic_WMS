    REVIEW_TEXT TEXT,
    VERIFIED_PURCHASE BOOLEAN NOT NULL DEFAULT FALSE,
    STATUS VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    CREATED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    PUBLISHED_DSTAMP TIMESTAMPTZ,
    CONSTRAINT FK_PRODUCT_REVIEW_PRODUCT
        FOREIGN KEY (CLIENT_ID,PRODUCT_ID)
        REFERENCES core.PRODUCT (CLIENT_ID,PRODUCT_ID)
