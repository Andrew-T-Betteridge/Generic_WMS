BEGIN;

CREATE SCHEMA IF NOT EXISTS config;
CREATE SCHEMA IF NOT EXISTS api;

CREATE TABLE IF NOT EXISTS config.SYSTEM_VERSION (
    VERSION_KEY BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_CODE VARCHAR(30) NOT NULL,
    PRODUCT_NAME VARCHAR(100) NOT NULL,
    VERSION_NUMBER VARCHAR(30) NOT NULL,
    VERSION_MAJOR INTEGER NOT NULL,
    VERSION_MINOR INTEGER NOT NULL,
    VERSION_PATCH INTEGER NOT NULL,
    BUILD_NUMBER INTEGER NOT NULL DEFAULT 0,
    RELEASE_CHANNEL VARCHAR(20) NOT NULL DEFAULT 'DEVELOPMENT',
    RELEASE_DATE DATE NOT NULL DEFAULT CURRENT_DATE,
    DESCRIPTION VARCHAR(500),
    IS_CURRENT BOOLEAN NOT NULL DEFAULT FALSE,
    INSTALLED_DSTAMP TIMESTAMPTZ NOT NULL DEFAULT now(),
    INSTALLED_BY VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    CONSTRAINT UQ_SYSTEM_VERSION UNIQUE (PRODUCT_CODE,VERSION_NUMBER)
);

CREATE UNIQUE INDEX IF NOT EXISTS UQ_SYSTEM_VERSION_CURRENT
    ON config.SYSTEM_VERSION (PRODUCT_CODE)
    WHERE IS_CURRENT = TRUE;

UPDATE config.SYSTEM_VERSION
SET IS_CURRENT = FALSE
WHERE PRODUCT_CODE='DYNETIC_WMS'
  AND IS_CURRENT=TRUE
  AND VERSION_NUMBER<>'0.1.0';

INSERT INTO config.SYSTEM_VERSION (
    PRODUCT_CODE,
    PRODUCT_NAME,
    VERSION_NUMBER,
    VERSION_MAJOR,
    VERSION_MINOR,
    VERSION_PATCH,
    BUILD_NUMBER,
    RELEASE_CHANNEL,
    RELEASE_DATE,
    DESCRIPTION,
    IS_CURRENT
)
VALUES (
    'DYNETIC_WMS',
    'DYNETIC WMS',
    '0.1.0',
    0,
    1,
    0,
    0,
    'DEVELOPMENT',
    CURRENT_DATE,
    'Initial branded DYNETIC WMS development baseline with generic warehouse execution and website commerce APIs.',
    TRUE
)
ON CONFLICT (PRODUCT_CODE,VERSION_NUMBER)
DO UPDATE SET
    PRODUCT_NAME=EXCLUDED.PRODUCT_NAME,
    VERSION_MAJOR=EXCLUDED.VERSION_MAJOR,
    VERSION_MINOR=EXCLUDED.VERSION_MINOR,
    VERSION_PATCH=EXCLUDED.VERSION_PATCH,
    BUILD_NUMBER=EXCLUDED.BUILD_NUMBER,
    RELEASE_CHANNEL=EXCLUDED.RELEASE_CHANNEL,
    RELEASE_DATE=EXCLUDED.RELEASE_DATE,
    DESCRIPTION=EXCLUDED.DESCRIPTION,
    IS_CURRENT=TRUE;

COMMIT;
