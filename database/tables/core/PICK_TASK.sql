-- PICK_TASK
-- Minimal executable warehouse work generated from durable allocation records.
CREATE TABLE IF NOT EXISTS core.PICK_TASK (
    PICK_TASK_ID             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENT_ID                VARCHAR(10) NOT NULL,
    ORDER_ID                 VARCHAR(20) NOT NULL,
    LINE_ID                  NUMERIC(6) NOT NULL,
    ALLOCATION_ID            BIGINT NOT NULL,
    INVENTORY_KEY            BIGINT NOT NULL,
    SKU_ID                   VARCHAR(50) NOT NULL,
    LOCATION_ID              VARCHAR(20) NOT NULL,
    BATCH_ID                 VARCHAR(50),
    QTY_REQUIRED             NUMERIC(15,6) NOT NULL,
    QTY_PICKED               NUMERIC(15,6) NOT NULL DEFAULT 0,
    SHORT_QTY                NUMERIC(15,6) NOT NULL DEFAULT 0,
    STATUS                   VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    SHORT_REASON             VARCHAR(120),
    CREATED_DSTAMP           TIMESTAMPTZ NOT NULL DEFAULT now(),
    STARTED_DSTAMP           TIMESTAMPTZ,
    COMPLETED_DSTAMP         TIMESTAMPTZ,
    LAST_UPDATE_DSTAMP       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CREATED_BY               VARCHAR(20) NOT NULL DEFAULT 'SYSTEM',
    LAST_UPDATED_BY          VARCHAR(20) NOT NULL DEFAULT 'SYSTEM',
    CONSTRAINT UQ_PICK_TASK_ALLOCATION UNIQUE (ALLOCATION_ID),
    CONSTRAINT FK_PICK_TASK_ORDER_LINE FOREIGN KEY (CLIENT_ID, ORDER_ID, LINE_ID)
        REFERENCES core.ORDER_LINE (CLIENT_ID, ORDER_ID, LINE_ID),
    CONSTRAINT FK_PICK_TASK_ALLOCATION FOREIGN KEY (ALLOCATION_ID)
        REFERENCES core.ALLOCATION (ALLOCATION_ID),
    CONSTRAINT FK_PICK_TASK_INVENTORY FOREIGN KEY (INVENTORY_KEY)
        REFERENCES core.INVENTORY (KEY),
    CONSTRAINT FK_PICK_TASK_SKU FOREIGN KEY (CLIENT_ID, SKU_ID)
        REFERENCES core.SKU (CLIENT_ID, SKU_ID),
    CONSTRAINT FK_PICK_TASK_LOCATION FOREIGN KEY (LOCATION_ID)
        REFERENCES core.LOCATION (LOCATION_ID),
    CONSTRAINT CK_PICK_TASK_QTY CHECK (
        QTY_REQUIRED > 0 AND QTY_PICKED >= 0 AND SHORT_QTY >= 0
        AND QTY_PICKED + SHORT_QTY <= QTY_REQUIRED
    )
);

COMMENT ON TABLE core.PICK_TASK IS
    'Minimal warehouse execution work: what order/line/SKU/inventory/location/quantity must be picked and its execution state.';
