CREATE TABLE IF NOT EXISTS core.ORDER_CONTAINER (
    CONTAINER_KEY bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CLIENT_ID varchar(30) NOT NULL REFERENCES core.CLIENT(CLIENT_ID),
    ORDER_ID varchar(50) NOT NULL,
    CONTAINER_ID varchar(80) NOT NULL,
    CONTAINER_TYPE varchar(40),
    STATUS varchar(30) NOT NULL DEFAULT 'OPEN',
    WEIGHT numeric(14,3),
    HEIGHT numeric(14,3),
    WIDTH numeric(14,3),
    DEPTH numeric(14,3),
    VOLUME numeric(18,3),
    CARRIER_ID varchar(30),
    SERVICE_LEVEL varchar(50),
    TRACKING_NUMBER varchar(100),
    CREATED_DSTAMP timestamptz NOT NULL DEFAULT now(),
    CLOSED_DSTAMP timestamptz,
    UNIQUE (CLIENT_ID, CONTAINER_ID),
    FOREIGN KEY (CLIENT_ID, ORDER_ID) REFERENCES core.ORDER_HEADER(CLIENT_ID, ORDER_ID)
);
