-- INVENTORY_TRANSACTION
-- Generic WMS inventory transaction history.
-- Allocation reservations are represented by core.ALLOCATION and
-- INVENTORY.QTY_ALLOCATED; this table remains for inventory-changing events.

CREATE TABLE IF NOT EXISTS core.INVENTORY_TRANSACTION (
    KEY                            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CODE                           VARCHAR(40) NOT NULL,
    SITE_ID                        VARCHAR(10),
    FROM_SITE_ID                   VARCHAR(10),
    TO_SITE_ID                     VARCHAR(10),
    FROM_LOC_ID                    VARCHAR(20),
    TO_LOC_ID                      VARCHAR(20),
    FINAL_LOC_ID                   VARCHAR(20),
    OWNER_ID                       VARCHAR(10),
    CLIENT_ID                      VARCHAR(10),
    SKU_ID                         VARCHAR(50),
    TAG_ID                         VARCHAR(50),
    CONTAINER_ID                   VARCHAR(50),
    BATCH_ID                       VARCHAR(50),
    QC_STATUS                      VARCHAR(20),
    EXPIRY_DSTAMP                  TIMESTAMPTZ,
    MANUF_DSTAMP                   TIMESTAMPTZ,
    ORIGIN_ID                      VARCHAR(10),
    CONDITION_ID                   VARCHAR(10),
    LOCK_STATUS                    VARCHAR(20),
    DSTAMP                         TIMESTAMPTZ NOT NULL,
    CONSIGNMENT                    VARCHAR(20),
    SUPPLIER_ID                    VARCHAR(15),
    REFERENCE_ID                   VARCHAR(20),
    LINE_ID                        NUMERIC(6),
    REASON_ID                      VARCHAR(10),
    STATION_ID                     VARCHAR(256) NOT NULL,
    USER_ID                        VARCHAR(20) NOT NULL,
    UPDATE_QTY                     NUMERIC(15,6) NOT NULL,
    ORIGINAL_QTY                   NUMERIC(15,6),
    COMPLETE_DSTAMP                TIMESTAMPTZ,
    NOTES                          VARCHAR(400),
    LOCK_CODE                      VARCHAR(10),
    CUSTOMER_ID                    VARCHAR(15),
    SHIPMENT_NUMBER                NUMERIC(10),
    FROM_STATUS                    VARCHAR(15),
    TO_STATUS                      VARCHAR(15),
    SOURCE                         VARCHAR(30),
    REFERENCE_TYPE                 VARCHAR(30),
    PRIMARY KEY (KEY)
);
